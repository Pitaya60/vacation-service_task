import { describe, it, expect } from 'vitest';
import { accrued, validateParts, checkBalance } from '../src/rules';
const P = (start: string, end: string) => ({ start, end });

describe('начисление', () => {
  it('28 дней за 365 отработанных', () => expect(accrued('2025-01-01', '2026-01-01')).toBe(28));
  it('до выхода — 0', () => expect(accrued('2025-01-10', '2025-01-01')).toBe(0));
  it('смена даты выхода меняет результат', () =>
    expect(accrued('2025-06-01', '2026-01-01')).toBeLessThan(accrued('2025-01-01', '2026-01-01')));
});
describe('дробление', () => {
  it('нет части от 14', () => expect(validateParts([P('2026-07-01', '2026-07-07'), P('2026-08-01', '2026-08-07')])).toBe('В заявке нет части от 14 дней.'));
  it('часть короче 5', () => expect(validateParts([P('2026-07-01', '2026-07-14'), P('2026-08-01', '2026-08-03')])).toMatch(/не короче 5/));
  it('больше 3 частей', () => expect(validateParts([1, 2, 3, 4].map((i) => P(`2026-0${i + 1}-01`, `2026-0${i + 1}-14`)))).toMatch(/Не более 3/));
  it('пересечение', () => expect(validateParts([P('2026-07-01', '2026-07-14'), P('2026-07-10', '2026-07-20')])).toMatch(/пересекаются/));
  it('валидно: 14 + 7', () => expect(validateParts([P('2026-07-01', '2026-07-14'), P('2026-08-01', '2026-08-07')])).toBeNull());
});
describe('остаток', () => {
  it('превышение накопленного отклоняется', () => expect(checkBalance('2026-01-01', [], [P('2026-02-01', '2026-02-14')])).toMatch(/накоплено/));
  it('хватает — проходит', () => expect(checkBalance('2025-01-01', [], [P('2026-02-01', '2026-02-14')])).toBeNull());
  it('учитывает уже взятое', () => expect(checkBalance('2025-06-01', [P('2026-01-05', '2026-01-25')], [P('2026-02-01', '2026-02-14')])).toMatch(/накоплено/));
});
